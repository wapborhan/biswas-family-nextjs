/**
 * Returns options for react-select / CreatableSelect:
 * Array of { value, label, postCode }
 */
export const getPostOfficeOptions = (
  divisionName,
  districtName,
  upazilaName,
) => {
  if (!upazilaName) return [];

  const trimmedUpazila = upazilaName.trim();

  // 1. Exact match in dictionary
  let list = bangladeshPostOffices[trimmedUpazila];

  // 2. Case-insensitive or partial match
  if (!list || list.length === 0) {
    const key = Object.keys(bangladeshPostOffices).find(
      (k) =>
        k.toLowerCase() === trimmedUpazila.toLowerCase() ||
        k.includes(trimmedUpazila) ||
        trimmedUpazila.includes(k),
    );
    if (key) {
      list = bangladeshPostOffices[key];
    }
  }

  // 3. If matched list exists, return mapped options
  if (list && list.length > 0) {
    return list.map((po) => ({
      value: po.name,
      label: `${po.name} (${po.code})`,
      postCode: po.code,
    }));
  }

  // 4. Fallback if upazila not found in dictionary: use district default postal code
  const defaultCode =
    (districtName && districtDefaultPostalCodes[districtName.trim()]) || "";

  return [
    {
      value: `${trimmedUpazila} সদর`,
      label: defaultCode
        ? `${trimmedUpazila} সদর (${defaultCode})`
        : `${trimmedUpazila} সদর`,
      postCode: defaultCode,
    },
  ];
};
