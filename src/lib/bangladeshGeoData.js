// Helper functions for easy consumption in components
export const getDivisionOptions = () =>
  bangladeshGeoData.map((d) => ({
    value: d.division,
    label: `${d.division} (${d.divisionEn})`,
  }));

export const getDistrictOptions = (divisionName) => {
  if (!divisionName) return [];
  const div = bangladeshGeoData.find(
    (d) =>
      d.division.toLowerCase() === divisionName.toLowerCase() ||
      d.divisionEn.toLowerCase() === divisionName.toLowerCase()
  );
  if (!div) return [];
  return div.districts.map((dist) => ({
    value: dist.district,
    label: `${dist.district} (${dist.districtEn})`,
  }));
};

export const getUpazilaOptions = (divisionName, districtName) => {
  if (!districtName) return [];
  const div = bangladeshGeoData.find(
    (d) =>
      !divisionName ||
      d.division.toLowerCase() === divisionName.toLowerCase() ||
      d.divisionEn.toLowerCase() === divisionName.toLowerCase()
  );
  const districts = div ? div.districts : bangladeshGeoData.flatMap((d) => d.districts);
  const dist = districts.find(
    (dist) =>
      dist.district.toLowerCase() === districtName.toLowerCase() ||
      dist.districtEn.toLowerCase() === districtName.toLowerCase()
  );
  if (!dist) return [];
  return dist.upazilas.map((u) => ({
    value: u,
    label: u,
  }));
};

